    public static List<String> generateToList(String input) {
        List<String> list = new LinkedList();
        // 按换行符分割字符串（兼容不同系统的换行符）
        String[] lines = input.split("\\r?\\n");

        for (int i = 0; i < lines.length; i++) {
            String line = lines[i].trim(); // 去除首尾空格
            String result = getAll(line);
            if (!line.isEmpty()) {
                list.add(result);
            }
        }
        return list;
    }

    public static String getAll(String md5Lower){
        StringBuilder mixed = new StringBuilder();

        for (int i = 0; i < md5Lower.length(); i++) {
            char c = md5Lower.charAt(i);
            // 每3个字符将第3个转为大写
            if ((i + 1) % 3 == 0 && Character.isLetter(c)) {
                c = Character.toUpperCase(c);
            }
            mixed.append(c);
        }
        return mixed.toString();
    }
